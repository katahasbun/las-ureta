-- Las Ureta · Tabla de presupuestos
-- Pegar completo en Supabase → SQL Editor → New query → Run.
-- Se puede ejecutar más de una vez sin duplicar nada.

-- Presupuestos guardados desde el cotizador. Tienen numeración propia (P-1, P-2…)
-- y no usan números de orden de trabajo.
create table if not exists presupuestos (
  id          bigint generated by default as identity primary key,
  datos       jsonb not null default '{}'::jsonb,
  estado      text not null default 'Pendiente',   -- Pendiente / Aceptado
  ot          bigint,                               -- N° de la orden creada al aceptarlo
  creado      timestamptz not null default now(),
  actualizado timestamptz not null default now(),
  creado_por  uuid default auth.uid() references auth.users (id)
);

create index if not exists presupuestos_creado_idx on presupuestos (creado desc);

-- Fecha de la última modificación
create or replace function marcar_presupuesto() returns trigger
language plpgsql as $$
begin
  new.actualizado := now();
  return new;
end $$;

drop trigger if exists presupuestos_actualizacion on presupuestos;
create trigger presupuestos_actualizacion before update on presupuestos
  for each row execute function marcar_presupuesto();

-- Seguridad: solo usuarias con sesión iniciada. No se borran desde el portal.
alter table presupuestos enable row level security;

drop policy if exists "equipo ve presupuestos" on presupuestos;
create policy "equipo ve presupuestos" on presupuestos
  for select to authenticated using (true);

drop policy if exists "equipo crea presupuestos" on presupuestos;
create policy "equipo crea presupuestos" on presupuestos
  for insert to authenticated with check (true);

drop policy if exists "equipo edita presupuestos" on presupuestos;
create policy "equipo edita presupuestos" on presupuestos
  for update to authenticated using (true) with check (true);

revoke all on presupuestos from anon;
grant select, insert, update on presupuestos to authenticated;
